-- =====================================================================
-- V1: Esquema inicial del MVP eCommerce B2B
-- =====================================================================

-- ---------------------------------------------------------------------
-- Usuarios (distribuidores, clientes autorizados y administradores)
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo               VARCHAR(150) NOT NULL,
    contrasena_hash      VARCHAR(100) NOT NULL,
    nombre_completo      VARCHAR(150) NOT NULL,
    razon_social         VARCHAR(150) NOT NULL,
    rfc                  VARCHAR(13)  NOT NULL,
    rol                  VARCHAR(20)  NOT NULL,
    activo               BOOLEAN      NOT NULL DEFAULT TRUE,
    id_cliente_crm       VARCHAR(50),
    fecha_creacion       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_actualizacion  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_usuarios_correo UNIQUE (correo),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ADMIN', 'DISTRIBUTOR', 'CUSTOMER'))
);

-- ---------------------------------------------------------------------
-- Catálogo de productos
-- ---------------------------------------------------------------------
CREATE TABLE productos (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                  VARCHAR(40)    NOT NULL,
    nombre               VARCHAR(150)   NOT NULL,
    descripcion          VARCHAR(1000),
    categoria            VARCHAR(80)    NOT NULL,
    precio               NUMERIC(12, 2) NOT NULL,
    existencias          INTEGER        NOT NULL,
    activo               BOOLEAN        NOT NULL DEFAULT TRUE,
    version              BIGINT         NOT NULL DEFAULT 0,
    fecha_creacion       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    fecha_actualizacion  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_productos_sku UNIQUE (sku),
    CONSTRAINT ck_productos_precio CHECK (precio >= 0),
    CONSTRAINT ck_productos_existencias CHECK (existencias >= 0)
);

CREATE INDEX ix_productos_categoria ON productos (categoria);

-- ---------------------------------------------------------------------
-- Carrito (uno por usuario)
-- ---------------------------------------------------------------------
CREATE TABLE carritos (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id           BIGINT      NOT NULL,
    fecha_creacion       TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_actualizacion  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_carritos_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_carritos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE TABLE carrito_detalles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrito_id   BIGINT  NOT NULL,
    producto_id  BIGINT  NOT NULL,
    cantidad     INTEGER NOT NULL,
    CONSTRAINT uk_carrito_detalles_carrito_producto UNIQUE (carrito_id, producto_id),
    CONSTRAINT fk_carrito_detalles_carrito FOREIGN KEY (carrito_id) REFERENCES carritos (id) ON DELETE CASCADE,
    CONSTRAINT fk_carrito_detalles_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT ck_carrito_detalles_cantidad CHECK (cantidad > 0)
);

-- ---------------------------------------------------------------------
-- Pedidos
-- ---------------------------------------------------------------------
CREATE TABLE pedidos (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio                   VARCHAR(40)    NOT NULL,
    usuario_id              BIGINT         NOT NULL,
    estatus                 VARCHAR(30)    NOT NULL,
    total                   NUMERIC(12, 2) NOT NULL,
    llave_idempotencia      VARCHAR(100)   NOT NULL,
    id_pedido_erp           VARCHAR(50),
    fecha_entrega_estimada  DATE,
    fecha_entrega           TIMESTAMPTZ,
    version                 BIGINT         NOT NULL DEFAULT 0,
    fecha_creacion          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    fecha_actualizacion     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_pedidos_folio UNIQUE (folio),
    -- Evita pedidos duplicados: el mismo usuario no puede repetir la misma llave de idempotencia
    CONSTRAINT uk_pedidos_usuario_llave UNIQUE (usuario_id, llave_idempotencia),
    CONSTRAINT fk_pedidos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_pedidos_total CHECK (total >= 0),
    CONSTRAINT ck_pedidos_estatus CHECK (estatus IN (
        'PENDING_PAYMENT', 'PAYMENT_FAILED', 'PAID', 'CONFIRMED',
        'SHIPPED', 'DELIVERED', 'CANCELLED'))
);

CREATE INDEX ix_pedidos_usuario ON pedidos (usuario_id);
CREATE INDEX ix_pedidos_estatus ON pedidos (estatus);

CREATE TABLE pedido_detalles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT         NOT NULL,
    producto_id      BIGINT         NOT NULL,
    sku              VARCHAR(40)    NOT NULL,
    nombre_producto  VARCHAR(150)   NOT NULL,
    precio_unitario  NUMERIC(12, 2) NOT NULL,
    cantidad         INTEGER        NOT NULL,
    subtotal         NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_pedido_detalles_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id) ON DELETE CASCADE,
    CONSTRAINT fk_pedido_detalles_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT ck_pedido_detalles_cantidad CHECK (cantidad > 0)
);

CREATE INDEX ix_pedido_detalles_pedido ON pedido_detalles (pedido_id);
CREATE INDEX ix_pedido_detalles_producto ON pedido_detalles (producto_id);

-- ---------------------------------------------------------------------
-- Pagos (intentos contra la pasarela)
-- ---------------------------------------------------------------------
CREATE TABLE pagos (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id            BIGINT         NOT NULL,
    monto                NUMERIC(12, 2) NOT NULL,
    estatus              VARCHAR(20)    NOT NULL,
    referencia_pasarela  VARCHAR(100),
    motivo_rechazo       VARCHAR(255),
    intentos             INTEGER        NOT NULL DEFAULT 1,
    fecha_creacion       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT fk_pagos_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT ck_pagos_estatus CHECK (estatus IN ('APPROVED', 'DECLINED', 'FAILED'))
);

CREATE INDEX ix_pagos_pedido ON pagos (pedido_id);
-- Solo puede existir UN pago aprobado por pedido (evita cobros dobles)
CREATE UNIQUE INDEX ux_pagos_pedido_aprobado ON pagos (pedido_id) WHERE estatus = 'APPROVED';

-- ---------------------------------------------------------------------
-- Outbox: eventos pendientes de sincronizar con ERP / CRM
-- ---------------------------------------------------------------------
CREATE TABLE eventos_outbox (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_agregado            VARCHAR(50)  NOT NULL,
    id_agregado              VARCHAR(50)  NOT NULL,
    destino                  VARCHAR(10)  NOT NULL,
    tipo_evento              VARCHAR(50)  NOT NULL,
    contenido                TEXT         NOT NULL,
    estatus                  VARCHAR(20)  NOT NULL,
    intentos                 INTEGER      NOT NULL DEFAULT 0,
    ultimo_error             VARCHAR(500),
    fecha_siguiente_intento  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_creacion           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_procesado          TIMESTAMPTZ,
    CONSTRAINT ck_eventos_outbox_destino CHECK (destino IN ('ERP', 'CRM')),
    CONSTRAINT ck_eventos_outbox_estatus CHECK (estatus IN ('PENDING', 'PROCESSED', 'FAILED'))
);

CREATE INDEX ix_eventos_outbox_pendientes ON eventos_outbox (estatus, fecha_siguiente_intento);